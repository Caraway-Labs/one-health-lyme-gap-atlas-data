-- Reviewed account-level PROD bootstrap for ADR 0041. Execute once with an
-- explicitly authorized administrative named snow connection after verifying
-- CURRENT_USER/ROLE/DATABASE/WAREHOUSE. This is not a schema migration:
-- the protected migration role lacks account CREATE ROLE and READ SESSION.
-- Never use this file for DEV or assign runtime/reviewer to a user here.

CREATE ROLE IF NOT EXISTS OH_LYME_PROD_DATASET_DISCOVERY_RUNTIME;
CREATE ROLE IF NOT EXISTS OH_LYME_PROD_DATASET_DISCOVERY_REVIEWER;
CREATE ROLE IF NOT EXISTS OH_LYME_PROD_DATASET_DISCOVERY_WRITE_OWNER;

-- Only the non-login procedure owner may inspect the invoking session in
-- owner-rights review/handoff procedures. Runtime and reviewer get no READ SESSION.
GRANT READ SESSION ON ACCOUNT
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_WRITE_OWNER;

-- Snowflake requires the ownership-transfer target to be in the deployer's
-- active role hierarchy. Do not grant this role to routine users or services.
GRANT ROLE OH_LYME_PROD_DATASET_DISCOVERY_WRITE_OWNER
  TO ROLE OH_LYME_PROD_MIGRATION_DEPLOYER;

-- These objects are owned outside the protected migration role. Grant only
-- the capabilities required to reach the narrow V114-owned objects/procedures.
GRANT USAGE ON DATABASE ONE_HEALTH_LYME_GAP_ATLAS_PROD
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_WRITE_OWNER;
GRANT USAGE ON DATABASE ONE_HEALTH_LYME_GAP_ATLAS_PROD
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_RUNTIME;
GRANT USAGE ON DATABASE ONE_HEALTH_LYME_GAP_ATLAS_PROD
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_REVIEWER;
GRANT USAGE ON SCHEMA ONE_HEALTH_LYME_GAP_ATLAS_PROD.GOVERNANCE
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_WRITE_OWNER;
GRANT USAGE ON SCHEMA ONE_HEALTH_LYME_GAP_ATLAS_PROD.GOVERNANCE
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_REVIEWER;
GRANT SELECT ON TABLE ONE_HEALTH_LYME_GAP_ATLAS_PROD.GOVERNANCE.CATALOG_DATASETS
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_WRITE_OWNER;
-- DATA #510: V126 must delegate these two account-owned catalog reads to
-- WRITE_OWNER. The migration deployer owns neither table, so only these exact
-- SELECT privileges receive grant option; no schema-wide authority is added.
GRANT SELECT ON TABLE ONE_HEALTH_LYME_GAP_ATLAS_PROD.GOVERNANCE.CATALOG_DISCOVERY_OBSERVATIONS
  TO ROLE OH_LYME_PROD_MIGRATION_DEPLOYER WITH GRANT OPTION;
GRANT SELECT ON TABLE ONE_HEALTH_LYME_GAP_ATLAS_PROD.GOVERNANCE.CATALOG_RESOURCES
  TO ROLE OH_LYME_PROD_MIGRATION_DEPLOYER WITH GRANT OPTION;
GRANT USAGE ON WAREHOUSE OH_LYME_PROD_INGEST_XS_WH
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_RUNTIME;
GRANT USAGE ON WAREHOUSE OH_LYME_PROD_INGEST_XS_WH
  TO ROLE OH_LYME_PROD_DATASET_DISCOVERY_REVIEWER;
