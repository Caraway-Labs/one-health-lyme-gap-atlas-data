USE DATABASE {{ DATABASE }};

CREATE TABLE IF NOT EXISTS RAW.CENSUS_COUNTY_ADJACENCY_2025 (
    SOURCE_SHA256 VARCHAR(64) NOT NULL,
    COUNTY_NAME VARCHAR NOT NULL,
    COUNTY_GEOID VARCHAR NOT NULL,
    NEIGHBOR_NAME VARCHAR NOT NULL,
    NEIGHBOR_GEOID VARCHAR NOT NULL,
    BOUNDARY_LENGTH_TEXT VARCHAR NOT NULL,
    INGESTION_RUN_ID VARCHAR NOT NULL,
    SOURCE_URL VARCHAR NOT NULL,
    SOURCE_FILE_NAME VARCHAR NOT NULL,
    SOURCE_VINTAGE VARCHAR NOT NULL,
    LICENSE_BASIS VARCHAR NOT NULL,
    RETRIEVED_AT TIMESTAMP_LTZ NOT NULL,
    CONSTRAINT CENSUS_COUNTY_ADJACENCY_2025_PK
        PRIMARY KEY (SOURCE_SHA256, COUNTY_GEOID, NEIGHBOR_GEOID)
);

CREATE TABLE IF NOT EXISTS CONFORMED.COUNTY_ADJACENCY (
    RELEASE_ID VARCHAR NOT NULL,
    FIPS_A VARCHAR(5) NOT NULL,
    FIPS_B VARCHAR(5) NOT NULL,
    SHARED_BOUNDARY_M NUMBER(38, 6) NOT NULL,
    CONTACT_TYPE VARCHAR(8) NOT NULL,
    SOURCE_VINTAGE VARCHAR NOT NULL,
    SOURCE_SHA256 VARCHAR(64) NOT NULL,
    INGESTION_RUN_ID VARCHAR NOT NULL,
    CONSTRAINT COUNTY_ADJACENCY_PK PRIMARY KEY (RELEASE_ID, FIPS_A, FIPS_B),
    CONSTRAINT COUNTY_ADJACENCY_ORDER CHECK (FIPS_A < FIPS_B),
    CONSTRAINT COUNTY_ADJACENCY_FIPS_A CHECK (REGEXP_LIKE(FIPS_A, '^[0-9]{5}$')),
    CONSTRAINT COUNTY_ADJACENCY_FIPS_B CHECK (REGEXP_LIKE(FIPS_B, '^[0-9]{5}$')),
    CONSTRAINT COUNTY_ADJACENCY_CONTACT CHECK (CONTACT_TYPE IN ('EDGE', 'POINT'))
);

CREATE OR REPLACE VIEW PRESENTATION.COUNTY_ADJACENCY_V1 AS
SELECT RELEASE_ID,
       FIPS_A,
       FIPS_B,
       SHARED_BOUNDARY_M,
       CONTACT_TYPE,
       SOURCE_VINTAGE,
       SOURCE_SHA256,
       INGESTION_RUN_ID
FROM CONFORMED.COUNTY_ADJACENCY
WHERE RELEASE_ID = 'census-county-adjacency-2025-8233d2ae'
  AND SOURCE_VINTAGE = '2025'
  AND SOURCE_SHA256 = '8233d2aed342f62eb02bae9f9002ad1d8fc6bd82d739185eba8bad832bf8fc87';

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE RAW.CENSUS_COUNTY_ADJACENCY_2025
    TO ROLE OH_LYME_{{ ENV }}_RUNTIME;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE CONFORMED.COUNTY_ADJACENCY
    TO ROLE OH_LYME_{{ ENV }}_RUNTIME;
GRANT SELECT ON VIEW PRESENTATION.COUNTY_ADJACENCY_V1
    TO ROLE OH_LYME_{{ ENV }}_READ;
